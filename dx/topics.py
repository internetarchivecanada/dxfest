COMPILED = {k: re.compile("|".join(v[2]), re.I) for k, v in TOPICS.items()}

# Topics too generic to apply from one stray word: need 2+ distinct hits.
NEEDS_TWO = {"nuclear", "press-freedom", "archives", "craft-documentary", "business-of-docs", "law-safety", "career", "tech", "children",
             "democracy", "disinformation", "finance", "media-industry", "craft-investigation", "local-news",
             "labor", "health", "policing", "justice", "environment"}


def topics_for(text):
    out = []
    for k, rx in COMPILED.items():
        hits = {m.group(0).lower() for m in rx.finditer(text or "")}
        if not hits:
            continue
        if k in NEEDS_TWO and len(hits) < 2:
            continue
        out.append(k)
    return out


